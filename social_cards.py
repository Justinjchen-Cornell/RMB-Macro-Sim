_FONT_PATH = None
def _fp():
    global _FONT_PATH
    if _FONT_PATH:
        return _FONT_PATH
    import os as _os
    for p in (r"C:\Windows\Fonts\msyh.ttc", r"C:\Windows\Fonts\simhei.ttf"):
        if _os.path.exists(p):
            _FONT_PATH = p
            return p
    raise RuntimeError("no CJK font")


def _pil_font(size, bold=True):
    from PIL import ImageFont
    try:
        return ImageFont.truetype(_fp(), size, index=0 if bold else 0)
    except Exception:
        return ImageFont.truetype(_fp(), size)


def _pil_card(path, accent, title, sub, rows, footer):
    """rows: list of (text, color_hex, size, bold, value_text or None)"""
    from PIL import Image, ImageDraw
    W, H = 1200, 1200
    img = Image.new("RGB", (W, H), "#ffffff")
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, W, 12], fill=accent)
    d.text((70, 56), title, font=_pil_font(38), fill=INK)
    d.text((70, 130), sub, font=_pil_font(20), fill=MUT)
    y = 250
    for item in rows:
        txt, col, size, bold, val = item
        if val:
            d.rectangle([70, y - 34, 76, y + 10], fill=col)
            d.text((110, y - 32), txt, font=_pil_font(size, bold), fill=INK)
            vtxt = val
            vb = d.textbbox((0, 0), vtxt, font=_pil_font(size, bold))
            d.text((W - 70 - (vb[2] - vb[0]), y - 32), vtxt,
                   font=_pil_font(size, bold), fill=col)
            y += 74
        else:
            d.text((110, y - 32), txt, font=_pil_font(size, bold), fill=col)
            y += int(size * 1.9)
    d.text((70, H - 120), footer, font=_pil_font(15), fill=MUT)
    img.save(path)
    print("  [pil] %s" % path)


