def _img(w, h):
    fig = plt.figure(figsize=(w / 100.0, h / 100.0), facecolor=PAPER)
    ax = fig.add_axes([0, 0, 1, 1]); ax.axis("off")
    return fig, ax


def _txt(ax, x, y, s, size, color=INK, weight="normal", ha="left", va="top"):
    ax.text(x, y, s, fontsize=size, color=color, fontweight=weight,
            ha=ha, va=va, linespacing=1.55)


def _bar(ax, x, y0, v, w, c, maxabs):
    ax.add_patch(plt.Rectangle((x, y0 - 1.2), max(1, w * abs(v) / maxabs * 60),
                               2.4, facecolor=c, edgecolor="none"))
    ax.text(x + max(1, w * abs(v) / maxabs * 60) + 1, y0, "%+.1f%%" % v,
            fontsize=9.5, color=INK, va="center", fontweight="bold")


